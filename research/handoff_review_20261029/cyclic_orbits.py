"""Usage: python cyclic_orbits.py support13.tsv; TSV: pattern, coefficient.
Input can be regenerated by signed_support.cpp in primary-repo checkpoint
31a286a, research/LC004/2026-10-29-four-gap-cancellation/.
"""
import csv,itertools,json,sys
from collections import Counter,defaultdict

def canon(w):
 d={};return tuple(d.setdefault(a,len(d)) for a in w)
t={canon(tuple(map(int,r['pattern'].split(',')))):int(r['coefficient']) for r in csv.DictReader(open(sys.argv[1]),delimiter='\t')}
groups=defaultdict(dict)
for w,c in t.items():
 crossed=set()
 for i,j,k,l in itertools.combinations(range(len(w)),4):
  if w[i]==w[k] and w[j]==w[l] and w[i]!=w[j]:crossed.update([w[i],w[j]])
 if crossed:
  counts=Counter(w);groups[tuple(sorted(counts[a] for a in crossed))][w]=c
out=[]
for profile,table in groups.items():
 seen=set();weights=Counter();sizes=Counter()
 for w,c in table.items():
  orbit={canon(w[i:]+w[:i]) for i in range(len(w))}
  assert all(table.get(v)==c for v in orbit)
  if w in seen:continue
  seen.update(orbit);weights[c]+=1;sizes[len(orbit)]+=1
 out.append(dict(profile=profile,count=len(table),coefficient_sum=sum(table.values()),orbit_sizes=dict(sizes),orbit_coefficient_distribution=dict(weights)))
print(json.dumps(out,indent=2))
